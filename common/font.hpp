// The bitmap for c: printable ASCII, one of the Latin-1 codes above, any
// other code from 0xA0 up, or '?' for the control codes.
constexpr const u8* glyph(char c) {
    const u8 code = static_cast<u8>(c);
    if (code >= 0x20 && code <= 0x7E) {
        return kFont8x8[code - 0x20];
    }
    for (usize i = 0; i < sizeof(kFont8x8Latin1Codes) / sizeof(kFont8x8Latin1Codes[0]); ++i) {
        if (kFont8x8Latin1Codes[i] == code) {
            return kFont8x8Latin1[i];
        }
    }
    if (code >= 0xA0) {
        return kFont8x8ExtLatin1[code - 0xA0];
    }
    return kFont8x8['?' - 0x20];
}

