// The codes the rows of kFont8x8Latin1 are drawn for, in table order.
inline constexpr u8 kFont8x8Latin1Codes[16] = {
    0xC4, 0xC5, 0xD6, 0xE4, 0xE5, 0xF6, 0xC9, 0xE9, 0xDC, 0xFC, 0xA7, 0xA3, 0xA4, 0xBD, 0xB4, 0xA9,
};

// The bitmap for c, or the one for '?' when c is not printable ASCII and not
// one of the Latin-1 codes above.
inline const u8* glyph(char c) {
    const u8 code = static_cast<u8>(c);
    if (code >= 0x20 && code <= 0x7E) {
        return kFont8x8[code - 0x20];
    }
    for (usize i = 0; i < sizeof(kFont8x8Latin1Codes) / sizeof(kFont8x8Latin1Codes[0]); ++i) {
        if (kFont8x8Latin1Codes[i] == code) {
            return kFont8x8Latin1[i];
        }
    }
    return kFont8x8['?' - 0x20];
}

